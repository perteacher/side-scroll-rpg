// 몹 강도 배율.
//
// 몹 수치(js/data/world.js)는 사이드스크롤 시절에 잡은 값이다. 그 뒤로 파티 쪽에만
// 스탠스 성장·장비 강화·잠재능력·컬렉션·링크가 쌓여서, 측정해 보니 Lv1~45 구간의 몹이
// 전부 한 프레임(0.02초)에 죽었다. 그래서 몹 정의는 그대로 두고 여기서 배율만 곱한다.
//
// 목표: 몹 한 마리 처치에 1.5~3.5초. 경험치는 처치 속도가 2~3배 느려진 만큼만 올린다(성장 속도 유지).
// [레벨, HP 배율, 공격력 배율, 경험치 배율, 방어력 배율] — 사이 레벨은 선형 보간한다.
const ENEMY_SCALE_POINTS = [
  // 아래 값들은 '갓 시작한 파티'로 처음부터 플레이해 보며 다시 잡았다.
  // 예전 값은 스킬·스탠스를 다 올린 파티 기준이라, 실제로 시작하면 10~20레벨 구간에서 계속 전멸했다.
  [1, 12, 1.6, 1, 1],
  [5, 14, 1.6, 1, 1],
  [10, 22, 1.5, 1, 1],
  [15, 22, 1.4, 1, 1],
  [20, 30, 1.3, 1, 1],
  [25, 28, 1.3, 1, 1],
  [30, 34, 1.2, 1, 1],
  [35, 34, 1.2, 1, 1],
  [40, 36, 1.15, 1, 1],
  [45, 36, 1.15, 1, 1],
  // 50~95: 새로 만든 중반 사냥터 구간. 경험치 배율은 1로 두고 존 정의에 직접 적었다.
  [50, 33, 1.1, 1, 1],
  [60, 29, 1.0, 1, 1],
  [70, 24, 0.9, 1, 1],
  [80, 20, 0.8, 1, 1],
  [90, 15, 0.7, 1, 1],
  [95, 12.5, 0.62, 1, 1],
  // 100 이상은 레벨대 장비(베테랑~마스터)가 한참 세져서 다시 올려 잡았다.
  [100, 10, 0.55, 5, 0.9],
  [110, 2.2, 0.3, 6, 0.5],
  [120, 0.3, 0.25, 6, 0.2],
];

// 파티 구성이 '딜러 3'에서 '딜러 2 + 힐러 1'로 바뀌면서 처치 속도가 그만큼 느려졌다.
// 위 표의 성장 곡선(Lv1→10 약 3분 / 10→20 약 6분)은 딜러 3 기준으로 잰 값이라,
// 처치 속도가 줄어든 만큼 마리당 경험치를 올려 같은 속도를 유지한다.
// 힐러를 빼고 딜러만 세 명으로 다니면 그만큼 더 빨리 크는 대신 회복을 스스로 감당해야 한다.
const PARTY_XP_MULT = 1.4;

function enemyScaleFor(level) {
  const pts = ENEMY_SCALE_POINTS;
  const lv = clamp(level || 1, pts[0][0], pts[pts.length - 1][0]);
  let a = pts[0];
  let b = pts[pts.length - 1];
  for (let i = 0; i < pts.length - 1; i++) {
    if (lv >= pts[i][0] && lv <= pts[i + 1][0]) { a = pts[i]; b = pts[i + 1]; break; }
  }
  const span = b[0] - a[0];
  const t = span === 0 ? 0 : (lv - a[0]) / span;
  const mix = (i) => a[i] + (b[i] - a[i]) * t;
  return { hp: mix(1), atk: mix(2), xp: mix(3) * PARTY_XP_MULT, def: mix(4) };
}
