// 배경 도트 스프라이트. 캐릭터·몬스터·아이템과 같은 방식(픽셀 격자 + 팔레트)으로 배경도 찍는다.
// 모양은 한 번만 찍고 존 테마 색(far/mid/accent)을 팔레트로 갈아끼워 14개 테마에 돌려 쓴다.
//
// 공통 글자: a=밝은면  b=기본  c=어두운면  d=바닥 그림자  x=강조색(지붕·깃발·장식)  y=강조 밝은색
//           w=흰색(구름·창문)  v=그림자 흰색  h/j=나무(밝음/어두움, PIXEL_BASE 공용)

// 테마 색에서 배경 팔레트를 만든다. 존마다 색이 달라도 같은 모양을 쓴다.
function sceneryPalette(theme, layer = 'mid') {
  const base = layer === 'far' ? theme.far : theme.mid;
  return {
    a: shadeHex(base, 1.28),
    b: base,
    c: shadeHex(base, 0.74),
    d: shadeHex(base, 0.52),
    x: theme.accent,
    y: shadeHex(theme.accent, 1.3),
    w: '#fff6d8',
    v: shadeHex(base, 0.6),
  };
}

function cloudPalette() {
  return { w: '#ffffff', v: '#d7e3ee' };
}

// 지면 팔레트는 존의 바닥 색에서 뽑는다.
function groundPalette(groundColor) {
  return {
    a: shadeHex(groundColor, 1.22),
    b: groundColor,
    c: shadeHex(groundColor, 0.78),
    d: shadeHex(groundColor, 0.55),
  };
}

